package com.company;

public class Literals {
    static void main() {

        // Integer Literals
        byte b = 25;
        short s = 20;
        int a = 50;
        long l = 100;

        // Float Literals
        float f = 1.0f;

        // Double Literals
        double d = 1.0;

        // Character Literals
        char ch = 'a';

        // Boolean Literals
        boolean bol = true;

        // String Literals
        String str = "Kshitij";

        System.out.println(str);
    }
}
